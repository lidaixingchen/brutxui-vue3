/**
 * 邮箱格式校验（客户端宽松校验，用于表单提示）。
 *
 * 约束：仅 ASCII 合法邮箱字符——本地部分允许 `A-Z a-z 0-9 . _ % + -`，
 * 域名部分允许字母/数字/连字符，顶级域至少 2 位字母（TLD 长度 ≥ 2）。
 * 会拒绝：单字符 TLD（如 a@b.c）、空标签（如 a@b..c）、本地部分含空白/特殊符号等。
 *
 * 注意：仅作前端提示用途，不校验邮箱是否真实存在，也不应作为后端级别的严格校验。
 */
export const EMAIL_REGEX = /^[a-zA-Z0-9._%+-]+@[a-zA-Z0-9-]+(?:\.[a-zA-Z0-9-]+)*\.[a-zA-Z]{2,}$/
